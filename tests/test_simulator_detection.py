import json
from pathlib import Path

import pytest

from converter.api import detect_simulators, get_empty_template, get_parser_from_str, run_parser

TESTS_DIR = Path(__file__).parent


def test_no_files() -> None:
    """No simulator can run without files."""
    assert detect_simulators({}) == {
        "files": {},
        "simulators": {
            "shieldhit": {
                "possible": False,
                "reason": "Missing beam.dat, geo.dat, mat.dat, detect.dat",
                "missing": ["beam.dat", "geo.dat", "mat.dat", "detect.dat"],
            },
            "fluka": {"possible": False, "reason": "Missing fl_sim.inp", "missing": ["fl_sim.inp"]},
            "geant4": {
                "possible": False,
                "reason": "Missing geometry.gdml, run.mac",
                "missing": ["geometry.gdml", "run.mac"],
            },
        },
    }


@pytest.mark.parametrize(
    "simulator,project_path",
    [
        ("shieldhit", TESTS_DIR / "shieldhit" / "resources" / "project.json"),
        ("shieldhit", TESTS_DIR / "shieldhit" / "resources" / "project_with_sobp.json"),
        ("fluka", TESTS_DIR / "fluka" / "project.json"),
        ("fluka", TESTS_DIR / "fluka" / "project2.json"),
        ("fluka", TESTS_DIR / "fluka" / "project3.json"),
        ("fluka", TESTS_DIR / "fluka" / "project4.json"),
        ("geant4", TESTS_DIR / "geant4" / "resources" / "project.json"),
    ],
)
def test_files_generated_by_converter(simulator: str, project_path: Path) -> None:
    """Files generated by the converter are enough to run their simulator."""
    with open(project_path, "r") as file_handle:
        files = run_parser(get_parser_from_str(simulator), json.load(file_handle))

    result = detect_simulators(files)

    assert result["simulators"][simulator] == {"possible": True, "missing": []}
    assert all(file["issues"] == [] for file in result["files"].values())


def test_required_files_belong_to_their_simulator() -> None:
    """Only the exact required names are assigned to a simulator."""
    files = {
        "info.json": "{}",
        "beam.dat": "x",
        "geo.dat": "x",
        "mat.dat": "x",
        "detect.dat": "x",
        "sobp.dat": "x",
        "fl_sim.inp": "x",
        "my_sim.inp": "x",
        "geometry.gdml": "x",
        "run.mac": "x",
        "notes.txt": "x",
    }

    assert {name: file["simulator"] for name, file in detect_simulators(files)["files"].items()} == {
        "info.json": None,
        "beam.dat": "shieldhit",
        "geo.dat": "shieldhit",
        "mat.dat": "shieldhit",
        "detect.dat": "shieldhit",
        "sobp.dat": None,
        "fl_sim.inp": "fluka",
        "my_sim.inp": None,
        "geometry.gdml": "geant4",
        "run.mac": "geant4",
        "notes.txt": None,
    }


def test_mixed_files_with_downloaded_copy() -> None:
    """A downloaded copy gets a rename suggestion and does not count as the required file."""
    files = {
        "beam.dat": "NSTAT 1000 0",
        "geo.dat": "0 0 geometry",
        "detect.dat": "Geometry Cyl",
        "fl_sim.inp": "TITLE",
        "fl_sim (1).inp": "TITLE",
    }

    assert detect_simulators(files) == {
        "files": {
            "beam.dat": {"simulator": "shieldhit", "issues": []},
            "geo.dat": {"simulator": "shieldhit", "issues": []},
            "detect.dat": {"simulator": "shieldhit", "issues": []},
            "fl_sim.inp": {"simulator": "fluka", "issues": []},
            "fl_sim (1).inp": {
                "simulator": None,
                "issues": [
                    {
                        "severity": "warning",
                        "code": "copy_suffix",
                        "message": "Looks like a downloaded copy of fl_sim.inp",
                        "suggested_name": "fl_sim.inp",
                    }
                ],
            },
        },
        "simulators": {
            "shieldhit": {"possible": False, "reason": "Missing mat.dat", "missing": ["mat.dat"]},
            "fluka": {"possible": True, "missing": []},
            "geant4": {
                "possible": False,
                "reason": "Missing geometry.gdml, run.mac",
                "missing": ["geometry.gdml", "run.mac"],
            },
        },
    }


@pytest.mark.parametrize(
    "name,original_name",
    [
        ("fl_sim (1).inp", "fl_sim.inp"),
        ("fl_sim(1).inp", "fl_sim.inp"),
        ("fl_sim-2.inp", "fl_sim.inp"),
        ("fl_sim 2.inp", "fl_sim.inp"),
        ("fl_sim.inp2", "fl_sim.inp"),
        ("beam (3).dat", "beam.dat"),
        ("run.mac2", "run.mac"),
    ],
)
def test_copy_suffix(name: str, original_name: str) -> None:
    """Copy suffixes added by browsers are recognised."""
    assert detect_simulators({name: "x"})["files"][name]["issues"][0]["suggested_name"] == original_name


@pytest.mark.parametrize("name", ["fl_sim.inp", "beam.dat", "sim_2.inp", "my-beam.dat", "geometry.gdml"])
def test_no_copy_suffix(name: str) -> None:
    """Ordinary names do not get a rename suggestion."""
    assert detect_simulators({name: "x"})["files"][name]["issues"] == []


def test_file_content_is_never_checked() -> None:
    """Empty or arbitrary content does not block a simulator."""
    result = detect_simulators({"beam.dat": "", "geo.dat": "anything", "mat.dat": " \n", "detect.dat": ""})

    assert result["simulators"]["shieldhit"] == {"possible": True, "missing": []}
    assert all(file["issues"] == [] for file in result["files"].values())


def test_other_files_do_not_matter() -> None:
    """Extra files do not block a simulator."""
    files = {"fl_sim.inp": "x", "a.inp": "x", "beam.dat": "x", "notes.txt": "x"}

    assert detect_simulators(files)["simulators"]["fluka"] == {"possible": True, "missing": []}


@pytest.mark.parametrize(
    "simulator,names",
    [
        ("shieldhit", ["beam.dat", "geo.dat", "mat.dat", "detect.dat"]),
        ("fluka", ["fl_sim.inp"]),
        ("geant4", ["geometry.gdml", "run.mac"]),
    ],
)
def test_get_empty_template(simulator: str, names: list) -> None:
    """The template has the required files with empty content and is a new dict each time."""
    template = get_empty_template(simulator)

    assert template == {name: "" for name in names}
    template["extra.dat"] = "x"
    assert "extra.dat" not in get_empty_template(simulator)


def test_get_empty_template_for_unknown_simulator() -> None:
    """An unknown simulator raises ValueError."""
    with pytest.raises(ValueError):
        get_empty_template("topas")
